#media, suma total y producto de tres numeros

a= float(input('Introduzca el primer numero:'))
b= float(input('Introduzca el segundo numero:'))
c= float(input('Introduzca el tercer numero:'))

suma_total= a + b + c
media= suma_total/ 3
producto= a * b * c

print('La suma total de los tres numeros es de:', suma_total)
print('La media de los tres numeros es de:', media) 
print('El producto de los tres numeros es de:', producto)